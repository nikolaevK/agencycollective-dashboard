/**
 * "Download PDF" for one AI Analyst reply: a screenshot of the rendered
 * message (text, KPI cards, charts, tables) paginated onto A4 landscape.
 * Loaded on click only (html2canvas + jsPDF are large).
 */

/** Theme-dependent SVG paint properties (color feeds currentColor). */
const SVG_PAINTS = ["color", "fill", "stroke", "stop-color"];

export async function exportMessagePdf(el: HTMLElement): Promise<void> {
  const [html2canvas, { jsPDF }] = await Promise.all([import("html2canvas").then((m) => m.default), import("jspdf")]);

  const captureWidth = 1400;
  const canvas = await html2canvas(el, {
    scale: 1.5,
    useCORS: true,
    backgroundColor: "#ffffff",
    logging: false,
    width: captureWidth,
    windowWidth: captureWidth,
    // Controls (copy buttons, "show all rows") never belong in the document.
    ignoreElements: (node) => node instanceof HTMLElement && node.hasAttribute("data-pdf-ignore"),
    onclone: (doc, clone) => {
      // Always light: a dark-mode capture would print white text on white paper.
      doc.documentElement.classList.remove("dark");
      // Lay the clone out wide so tables get room; wrap cells instead of clipping.
      clone.style.width = `${captureWidth}px`;
      clone.style.maxWidth = `${captureWidth}px`;
      clone.style.overflow = "visible";
      clone.querySelectorAll<HTMLElement>("td, th").forEach((c) => {
        c.style.whiteSpace = "normal";
        c.style.wordBreak = "break-word";
        c.style.maxWidth = "300px";
      });
      clone.querySelectorAll<HTMLElement>("table").forEach((t) => {
        t.style.width = "100%";
        t.style.tableLayout = "auto";
      });
      // A table collapsed on screen ("Show all" is left out) still prints every row.
      clone.querySelectorAll("[data-collapsed]").forEach((row) => row.removeAttribute("hidden"));
      // html2canvas draws each <svg> as a standalone image and, for that, inlines
      // every SVG node's ON-SCREEN computed styles — custom properties and
      // paints included. With the app in dark mode that printed dark-theme
      // charts, light-gray axis text and white icons on white paper. Drop the
      // inlined variables / paints and re-resolve the paints in this light
      // clone (document order: parents are re-resolved before their children).
      const view = doc.defaultView;
      if (view) {
        clone.querySelectorAll<SVGElement>("svg, svg *").forEach((node) => {
          const style = node.style;
          for (let i = style.length - 1; i >= 0; i--) if (style[i].startsWith("--")) style.removeProperty(style[i]);
          for (const p of SVG_PAINTS) style.removeProperty(p);
          const computed = view.getComputedStyle(node);
          for (const p of SVG_PAINTS) style.setProperty(p, computed.getPropertyValue(p));
        });
      }
    },
  });

  // A4 landscape
  const margin = 10;
  const pdfWidth = 297;
  const pageHeight = 210;
  const contentWidth = pdfWidth - margin * 2;
  const imgHeight = (canvas.height * contentWidth) / canvas.width;
  const pdf = new jsPDF({ orientation: "l", unit: "mm", format: "a4", compress: true });

  pdf.setFontSize(8);
  pdf.setTextColor(113, 113, 122);
  pdf.text("AGENCY COLLECTIVE", margin, 8);
  pdf.setFontSize(14);
  pdf.setTextColor(24, 24, 27);
  pdf.text("AI Analyst Report", margin, 14);
  pdf.setFontSize(8);
  pdf.setTextColor(113, 113, 122);
  pdf.text(`Generated ${new Date().toLocaleDateString()}`, margin, 19);
  pdf.setDrawColor(228, 228, 231);
  pdf.setLineWidth(0.4);
  pdf.line(margin, 21, contentWidth + margin, 21);

  const headerHeight = 26;
  const overlapMm = 8; // repeat a strip at page boundaries so no line of text is cut
  let currentY = 0;
  let isFirstPage = true;

  while (currentY < imgHeight) {
    const yOffset = isFirstPage ? headerHeight : margin;
    const availableHeight = pageHeight - yOffset - margin;
    const sliceHeight = Math.min(imgHeight - currentY, availableHeight);
    const sourceY = currentY * (canvas.height / imgHeight);
    const sourceH = sliceHeight * (canvas.height / imgHeight);

    const pageCanvas = document.createElement("canvas");
    pageCanvas.width = canvas.width;
    pageCanvas.height = sourceH;
    const ctx = pageCanvas.getContext("2d");
    if (ctx) {
      ctx.drawImage(canvas, 0, sourceY, canvas.width, sourceH, 0, 0, canvas.width, sourceH);
      pdf.addImage(pageCanvas.toDataURL("image/jpeg", 0.85), "JPEG", margin, yOffset, contentWidth, sliceHeight);
    }

    currentY += sliceHeight - (currentY + sliceHeight < imgHeight ? overlapMm : 0);
    isFirstPage = false;
    if (currentY < imgHeight) pdf.addPage();
  }

  const lastPageHeight = pdf.internal.pageSize.getHeight();
  pdf.setFontSize(7);
  pdf.setTextColor(113, 113, 122);
  pdf.text("Generated by Agency Collective AI Analyst", margin, lastPageHeight - 6);
  pdf.text(new Date().toLocaleDateString(), contentWidth + margin - 20, lastPageHeight - 6);

  const blob = pdf.output("blob");
  const url = URL.createObjectURL(blob);
  // Preview in a new tab (print / save from there); popup blocked → download.
  const opened = window.open(url, "_blank");
  if (!opened) {
    const a = document.createElement("a");
    a.href = url;
    a.download = `ai-analyst-${new Date().toISOString().slice(0, 10)}.pdf`;
    document.body.appendChild(a);
    a.click();
    a.remove();
  }
  setTimeout(() => URL.revokeObjectURL(url), 60_000);
}
